#!/usr/bin/env bash
# Package an already-built SentinelAgent executable as a Finder-launchable app.
# This script deliberately does not rebuild or modify the agent executable.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
INPUT_BINARY="${1:-${REPO_ROOT}/dist/macos/SentinelAgent-macos-arm64}"
OUTPUT_APP="${2:-${REPO_ROOT}/dist/macos/SentinelAgent.app}"

if [[ ! -f "${INPUT_BINARY}" ]]; then
    echo "ERROR: executable not found: ${INPUT_BINARY}" >&2
    exit 1
fi

rm -rf "${OUTPUT_APP}"
LAUNCHER_SOURCE="$(mktemp -t sentinelagent-launcher).applescript"
cleanup() { rm -f "${LAUNCHER_SOURCE}"; }
trap cleanup EXIT

cat > "${LAUNCHER_SOURCE}" <<'APPLESCRIPT'
on run argv
    set appRoot to POSIX path of (path to me)
    set executablePath to appRoot & "Contents/MacOS/SentinelAgentLauncher"
    set commandLine to "cd " & quoted form of appRoot & " && " & quoted form of executablePath

    repeat with argumentValue in argv
        set commandLine to commandLine & " " & quoted form of (contents of argumentValue)
    end repeat

    -- Start the GUI as the logged-in user.  The packaging launcher below
    -- authorizes only the Settings view.
    do shell script commandLine
end run
APPLESCRIPT

# osacompile creates a normal .app bundle whose executable is the AppleScript
# applet.  The applet only launches the unchanged binary above.
osacompile -o "${OUTPUT_APP}" "${LAUNCHER_SOURCE}"

CONTENTS_DIR="${OUTPUT_APP}/Contents"
MACOS_DIR="${CONTENTS_DIR}/MacOS"
RESOURCES_DIR="${CONTENTS_DIR}/Resources"
mkdir -p "${MACOS_DIR}" "${RESOURCES_DIR}"

# Keep the exact standalone executable in the bundle.  It is not rebuilt,
# rewritten, or wrapped; only its location changes for Finder distribution.
cp -p "${INPUT_BINARY}" "${RESOURCES_DIR}/SentinelAgent"
chmod "$(stat -f '%Lp' "${INPUT_BINARY}")" "${RESOURCES_DIR}/SentinelAgent"

# The GUI must start as the logged-in user. The existing agent subsequently
# starts its background process by invoking its executable with --daemon. This
# packaging-only shim authorizes only the Settings view and runs the unchanged
# executable directly for normal GUI/daemon/watchdog arguments.
cat > "${MACOS_DIR}/SentinelAgentLauncher" <<'LAUNCHER'
#!/usr/bin/env bash
set -euo pipefail

LAUNCHER_PATH="$0"
REAL_EXECUTABLE="$(cd "$(dirname "$0")/../Resources" && pwd)/SentinelAgent"
export SENTINEL_AGENT_LAUNCHER="$LAUNCHER_PATH"

if [[ "${1:-}" == "--settings" ]] && [[ "${SENTINEL_AGENT_AUTHORIZED:-}" != "1" ]]; then
    /usr/bin/osascript - "$LAUNCHER_PATH" "$@" <<'APPLESCRIPT'
on run argv
    set launcherPath to item 1 of argv
    set commandLine to "/usr/bin/env SENTINEL_AGENT_AUTHORIZED=1 " & quoted form of launcherPath
    repeat with argumentValue in items 2 thru (count argv) of argv
        set commandLine to commandLine & " " & quoted form of (contents of argumentValue)
    end repeat
    do shell script commandLine with administrator privileges
end run
APPLESCRIPT
else
    # Preserve the launcher path as argv[0] so the agent's existing restart
    # and persistence paths continue to resolve through the app bundle.
    exec -a "$LAUNCHER_PATH" "$REAL_EXECUTABLE" "$@"
fi
LAUNCHER
chmod +x "${MACOS_DIR}/SentinelAgentLauncher"

# Include the source resource directory as a bundle resource as well.  The
# onefile executable already contains its compiled resources; this copy also
# keeps the app self-describing for any existing file/resource lookups.
if [[ -d "${REPO_ROOT}/resources" ]]; then
    cp -pR "${REPO_ROOT}/resources" "${RESOURCES_DIR}/resources"
fi

# Replace the generated metadata with stable application metadata and point
# Finder at the AppleScript launcher generated by osacompile.
cat > "${CONTENTS_DIR}/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleDevelopmentRegion</key>
    <string>en</string>
    <key>CFBundleDisplayName</key>
    <string>SentinelAgent</string>
    <key>CFBundleExecutable</key>
    <string>applet</string>
    <key>CFBundleIdentifier</key>
    <string>io.deepcytes.sentinelagent</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>CFBundleName</key>
    <string>SentinelAgent</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>1.0</string>
    <key>CFBundleVersion</key>
    <string>1</string>
    <key>LSMinimumSystemVersion</key>
    <string>11.0</string>
    <key>LSUIElement</key>
    <true/>
</dict>
</plist>
PLIST

chmod +x "${CONTENTS_DIR}/MacOS/applet"

echo "Created: ${OUTPUT_APP}"
echo "Executable: ${CONTENTS_DIR}/Resources/SentinelAgent"
